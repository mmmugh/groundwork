"""Export a volume as one Word document, generated from its pages.

    build/.work/docx-venv/bin/python scripts/make_docx.py [--volume DIR] [--out PATH]

The volume defaults to volumes/vol1 and the file to build/.work/docx/groundwork.docx.
Adapted from the Python course's scripts/make_docx.py (D24), and built from the pages
rather than from a draft, so it says what the course says now. It needs python-docx
(README.md says how to install it); the build does not.

The file ships with a release of the course, not as a page of the site, and this script
can run long after the build has checked site/, so the file checks itself (DESIGN.md
section 4): after saving, the site's own private-content scan runs inside it and deletes
it on a hit, and on macOS textutil must be able to read it.
"""

import json
import re
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

try:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Inches, Pt, RGBColor
except ImportError:
    sys.exit("python-docx is not installed for this Python. Make the venv README.md describes:\n"
             "  python3 -m venv build/.work/docx-venv && "
             "build/.work/docx-venv/bin/pip install python-docx==1.2.0\n"
             "and run this script with build/.work/docx-venv/bin/python")

ROOT = Path(__file__).resolve().parent.parent
COMMENTS = "generated by python-docx. Claude Opus 5.5"
BYLINE = "—built with Claude"
# Publish.docxHoldsAnAnswer's two markers: an answer key's own line, and the Python course's
# heading over its worked solutions.
MARKERS = ("ANSWER KEY", "Worked solutions")

# Volume.loadPages' file names.
FRONT = re.compile(r"00-.*\.md")
CHAPTER = re.compile(r"ch([0-9]+)-.*\.md")
APPENDIX = re.compile(r"99-.*\.md")

# build/Markdown.java's patterns, and Pages.PART.
FENCE_OPEN = re.compile(r"```[^`]*")
HEADING = re.compile(r"(#{1,3}) (.*)")
ORDERED_ITEM = re.compile(r"[0-9]+\. ")
DELIMITER_ROW = re.compile(r"[|:\- ]+")
CODE_SPAN = re.compile(r"`([^`]+)`")
BOLD = re.compile(r"\*\*([^*]+)\*\*")
ITALIC = re.compile(r"(?<!\*)\*([^*]+)\*(?!\*)")
LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
PART = re.compile(r"<!-- part: (.*) -->")

# What Java's String.trim() strips: every character up to and including the space.
TRIM = "".join(map(chr, range(0x21)))


def arguments(argv):
    """The volume and the output path, each named by its flag, at most once, never guessed.

    The Python course's script once told them apart by a ".docx" suffix, and so read an
    output path without one as a volume name; naming both leaves nothing to guess.
    """
    given = {}
    rest = list(argv)
    while rest:
        flag = rest.pop(0)
        if flag not in ("--volume", "--out"):
            sys.exit(f"unexpected argument {flag!r}; "
                     "usage: make_docx.py [--volume DIR] [--out PATH]")
        if flag in given:
            sys.exit(f"{flag} given twice: one volume, one output path")
        if not rest:
            sys.exit(f"{flag} needs a path after it")
        given[flag] = Path(rest.pop(0))
    return (given.get("--volume", ROOT / "volumes" / "vol1"),
            given.get("--out", ROOT / "build" / ".work" / "docx" / "groundwork.docx"))


def author():
    """The author's name as DESIGN.md's byline gives it: the text before "—built with
    Claude" on the one line that holds it, after that line's "Byline:" label.

    Read at run time so that neither this script nor its test writes the name:
    build/NameTest.java allows it in the three bylines alone.
    """
    design = (ROOT / "DESIGN.md").read_text(encoding="utf-8")
    lines = [line for line in design.splitlines() if BYLINE in line]
    if len(lines) != 1:
        sys.exit(f"DESIGN.md: expected one byline line holding {BYLINE!r}, found "
                 f"{len(lines)}; the .docx's Author is read from it")
    name = lines[0].split(BYLINE, 1)[0].rsplit("Byline:", 1)[-1].strip()
    if not name:
        sys.exit(f"DESIGN.md's byline line gives no name before {BYLINE!r}; "
                 "the .docx's Author is read from it")
    return name


def load_volume(folder):
    """volume.json's title and subtitle as one title, the pages, and the check declarations.

    The pages are Volume.loadPages' content pages, in its order: the front matter, the
    chapters by number, then the appendices. content/*.md only, so the practice pages are
    left out, as the Python course's .docx leaves them out; and never a file whose name
    starts with "_", which feeds the build rather than the reader (_solutions.md holds every
    worked solution). Anything else in content/ is refused, as the build refuses it.
    """
    meta_file = folder / "volume.json"
    if not meta_file.is_file():
        sys.exit(f"{folder}: no volume.json, so not a volume")
    meta = json.loads(meta_file.read_text(encoding="utf-8"))
    if not isinstance(meta, dict) or not isinstance(meta.get("title"), str) or not meta["title"]:
        sys.exit(f"{meta_file}: \"title\" is required")
    subtitle = meta.get("subtitle") if isinstance(meta.get("subtitle"), str) else ""
    title = ": ".join(x for x in (meta["title"], subtitle) if x)

    content = folder / "content"
    if not content.is_dir():
        sys.exit(f"{folder}: no content/ folder")
    front, chapters, appendices = [], {}, []
    for path in sorted(content.glob("*.md")):
        name = path.name
        if name.startswith("_"):
            continue
        if FRONT.fullmatch(name):
            front.append(path)
        elif APPENDIX.fullmatch(name):
            appendices.append(path)
        elif m := CHAPTER.fullmatch(name):
            number = int(m.group(1))
            if number in chapters:
                sys.exit(f"chapter {number}: both {chapters[number].name} and {name} claim it")
            chapters[number] = path
        else:
            sys.exit(f"{path}: not a front-matter, chapter or appendix file")
    pages = front + [chapters[n] for n in sorted(chapters)] + appendices
    if not pages:
        sys.exit(f"{content}: no pages")

    checks_file = content / "_checks.json"
    checks = json.loads(checks_file.read_text(encoding="utf-8")) if checks_file.is_file() else {}
    if not isinstance(checks, dict):
        sys.exit(f"{checks_file}: expected a JSON object")
    return title, pages, checks


def blocks(md, page):
    """build/Markdown.java's checkedBlocks, block for block, as (kind, payload) pairs.

    Kinds: heading (level, text), para (its lines joined with newlines), fence (lang,
    body), bullets (ordered, items), quote (text) and table (header, rows). Like the build,
    it refuses a fence that never closes, a fence of four or more backticks and a table
    with no delimiter row, rather than print them.
    """
    lines = md.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    out = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]

        if FENCE_OPEN.fullmatch(line):
            lang = line[3:].strip(TRIM)
            body = []
            i += 1
            closed = False
            while i < n:
                if lines[i] == "```":
                    closed = True
                    i += 1
                    break
                body.append(lines[i] + "\n")
                i += 1
            if not closed:
                sys.exit(f"{page}: unclosed fence ({lang or 'no language'})")
            out.append(("fence", (lang, "".join(body))))
            continue

        if line.startswith("````"):
            sys.exit(f"{page}: fences of four or more backticks are not supported "
                     "(the course uses three)")

        if not line.strip():
            i += 1
            continue

        heading = HEADING.fullmatch(line)
        if heading:
            out.append(("heading", (len(heading.group(1)), heading.group(2))))
            i += 1
            continue

        if line.startswith("|"):
            rows = []
            while i < n and lines[i].startswith("|"):
                rows.append(lines[i])
                i += 1
            if len(rows) < 2 or not DELIMITER_ROW.fullmatch(rows[1]):
                sys.exit(f"{page}: table without a delimiter row")
            out.append(("table", (table_row(rows[0]), [table_row(r) for r in rows[2:]])))
            continue

        if line.startswith(("- ", "* ")):
            items = []
            while i < n and lines[i].startswith(("- ", "* ")):
                items.append(lines[i][2:])
                i += 1
            out.append(("bullets", (False, items)))
            continue

        if ORDERED_ITEM.match(line):
            items = []
            while i < n and (m := ORDERED_ITEM.match(lines[i])):
                items.append(lines[i][m.end():])
                i += 1
            out.append(("bullets", (True, items)))
            continue

        if line.startswith("> "):
            out.append(("quote", line[2:]))
            i += 1
            continue

        para = []
        while (i < n and lines[i].strip() and not FENCE_OPEN.fullmatch(lines[i])
               and not lines[i].startswith("````")):
            para.append(lines[i])
            i += 1
        out.append(("para", "\n".join(para)))
    return out


def table_row(row):
    r = row.strip(TRIM)
    if r.startswith("|"):
        r = r[1:]
    if r.endswith("|"):
        r = r[:-1]
    return [c.strip(TRIM) for c in r.split("|")]


def spans(text):
    """Inline Markdown as (text, code, bold, italic) pieces, found as Markdown.inline finds
    them: code spans first, so nothing inside one is read as bold, italic or a link; then
    bold, then italic, then links, which keep their text and drop their target, as the
    Python course's .docx does."""
    code = []

    def stash(m):
        code.append(m.group(1))
        return f"\x00{len(code) - 1}\x00"

    text = CODE_SPAN.sub(stash, text)
    text = BOLD.sub(lambda m: "\x01" + m.group(1) + "\x02", text)
    text = ITALIC.sub(lambda m: "\x03" + m.group(1) + "\x04", text)
    text = LINK.sub(lambda m: m.group(1), text)

    pieces, bold, italic, at = [], False, False, 0
    for m in re.finditer(r"\x00([0-9]+)\x00|[\x01-\x04]", text):
        if m.start() > at:
            pieces.append((text[at:m.start()], False, bold, italic))
        at = m.end()
        if m.group(1) is not None:
            pieces.append((code[int(m.group(1))], True, bold, italic))
        elif m.group(0) in "\x01\x02":
            bold = m.group(0) == "\x01"
        else:
            italic = m.group(0) == "\x03"
    if at < len(text):
        pieces.append((text[at:], False, bold, italic))
    return pieces


def plain(text):
    """A heading's text: its inline markup read and dropped, as the Python course's .docx
    drops a heading's backticks."""
    return "".join(piece for piece, *_ in spans(text))


def add_runs(paragraph, text):
    """Inline markdown as runs: `code` in Menlo, **bold**, *italic*, and a link's text. A
    paragraph's lines join with a space, as they do in a browser."""
    for piece, code, bold, italic in spans(text.replace("\n", " ")):
        run = paragraph.add_run(piece)
        if code:
            run.font.name = "Menlo"
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor(0x8A, 0x30, 0x20)
        if bold:
            run.bold = True
        if italic:
            run.italic = True


def add_code(document, code, muted=False):
    """A fence: a program in Menlo, and anything else (its output, a terminal, a compiler's
    message) in Menlo, muted grey."""
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.left_indent = Inches(0.3)
    paragraph.paragraph_format.space_before = Pt(6)
    paragraph.paragraph_format.space_after = Pt(6)
    run = paragraph.add_run(code.rstrip("\n"))
    run.font.name = "Menlo"
    run.font.size = Pt(9)
    if muted:
        run.font.color.rgb = RGBColor(0x60, 0x60, 0x60)


def numbered_from_one(document, paragraphs):
    """Word numbers every "List Number" paragraph in one sequence, so a list would go on
    from the last one's number; each list gets a numbering of its own, from 1, as an <ol>
    on the site does."""
    numbering = document.part.numbering_part.element
    shared = document.styles["List Number"].element.pPr.numPr.numId.val
    num = numbering.add_num(numbering.num_having_numId(shared).abstractNumId.val)
    num.add_lvlOverride(ilvl=0).add_startOverride(1)
    for paragraph in paragraphs:
        numPr = paragraph._p.get_or_add_pPr().get_or_add_numPr()
        numPr.get_or_add_ilvl().val = 0
        numPr.get_or_add_numId().val = num.numId


def read_page(path):
    """A page's part label, when its first line is Pages.PART's comment, and its text
    without that line."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")
    first, _, rest = text.partition("\n")
    part = PART.fullmatch(first)
    return (part.group(1), rest) if part else (None, text)


def add_page(document, path, text, checks):
    """One page's blocks.

    A ```java fence is a box, numbered on its page as Boxes.of numbers it, and shows what
    the page's box shows (Pages.shown and Pages.stated): a box whose check declares a
    starter shows the starter and no stated output, since its own fence is the author's
    answer (D40(b)); a predict box holds back its stated output, the answer the reader
    predicts.
    """
    page = blocks(text, path.name)
    box = 0
    i = 0
    while i < len(page):
        kind, payload = page[i]
        i += 1
        if kind == "heading":
            level, words = payload
            document.add_heading(plain(words), level - 1)
        elif kind == "para":
            add_runs(document.add_paragraph(), payload)
        elif kind == "bullets":
            ordered, items = payload
            style = "List Number" if ordered else "List Bullet"
            paragraphs = [document.add_paragraph(style=style) for _ in items]
            for paragraph, item in zip(paragraphs, items):
                add_runs(paragraph, item)
            if ordered:
                numbered_from_one(document, paragraphs)
        elif kind == "quote":
            add_runs(document.add_paragraph(style="Intense Quote"), payload)
        elif kind == "table":
            header, rows = payload
            table = document.add_table(rows=0, cols=max(len(r) for r in [header, *rows]))
            table.style = "Light Grid Accent 1"
            for n, row in enumerate([header, *rows]):
                for cell, value in zip(table.add_row().cells, row):
                    add_runs(cell.paragraphs[0], value)
                    if n == 0:
                        for run in cell.paragraphs[0].runs:
                            run.bold = True
        elif kind == "fence":
            lang, body = payload
            if lang != "java":
                add_code(document, body, muted=True)
                continue
            box += 1
            check = checks.get(f"{path.stem}#{box}")
            check = check if isinstance(check, dict) else {}
            starter = check.get("starter") if isinstance(check.get("starter"), str) else None
            add_code(document, body if starter is None else starter)
            if i < len(page) and page[i][0] == "fence" and page[i][1][0] in ("", "output"):
                stated = page[i][1][1]
                i += 1
                if starter is None and check.get("kind") != "predict":
                    add_code(document, stated, muted=True)


def scan(out, pages, checks):
    """Publish.docxHoldsAnAnswer, on the file just written: word/document.xml must hold
    neither marker. On a hit the file is deleted, and the message names the marker and
    what holds it: the pages (a paragraph's lines joined with spaces), or a starter."""
    with zipfile.ZipFile(out) as archive:
        body = archive.read("word/document.xml").decode("utf-8", "replace")
    found = [m for m in MARKERS if m in body]
    if not found:
        return
    out.unlink()
    lines = []
    for marker in found:
        holders = [p.name for p in pages
                   if marker in p.read_text(encoding="utf-8").replace("\n", " ")]
        holders += [f"the starter of {box} (_checks.json)" for box, check in checks.items()
                    if isinstance(check, dict) and marker in str(check.get("starter", ""))]
        where = ", ".join(holders) or "the document, though no page or starter holds it as written"
        lines.append(f"  {marker!r} in {where}")
    sys.exit("the .docx would publish what must never be published (DESIGN.md section 4):\n"
             + "\n".join(lines) + f"\n{out} was deleted")


def open_check(out, title):
    """On macOS, textutil must read the file and find the title in its text; elsewhere this
    says it did not run, rather than passing in silence."""
    if sys.platform != "darwin":
        print(f"open check skipped: it uses macOS's textutil, and this is {sys.platform}")
        return
    try:
        done = subprocess.run(["textutil", "-convert", "txt", "-stdout", str(out)],
                              capture_output=True)
    except FileNotFoundError:
        sys.exit("open check failed: textutil is not on PATH; it ships with macOS")
    if done.returncode != 0:
        sys.exit(f"open check failed: textutil exited {done.returncode} reading {out} "
                 "(left for a look): " + done.stderr.decode("utf-8", "replace").strip())
    if title not in done.stdout.decode("utf-8", "replace"):
        sys.exit(f"open check failed: textutil read {out} (left for a look), but its text "
                 f"does not hold the title {title!r}")
    print("open check: textutil reads it, and its text holds the title")


def main():
    volume, out = arguments(sys.argv[1:])
    name = author()
    title, pages, checks = load_volume(volume)

    document = Document()
    document.core_properties.title = title
    document.core_properties.author = name
    document.core_properties.comments = COMMENTS
    # python-docx's template would otherwise date the file 2013-12-23.
    made = datetime.now(timezone.utc).replace(microsecond=0)
    document.core_properties.created = made
    document.core_properties.modified = made

    style = document.styles["Normal"]
    style.font.name = "Georgia"
    style.font.size = Pt(11)

    seen_parts = set()
    for n, path in enumerate(pages):
        part, text = read_page(path)
        if part is not None and part not in seen_parts:
            seen_parts.add(part)
            if n:
                document.add_page_break()
            heading = document.add_paragraph()
            heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = heading.add_run(plain(part))
            run.bold = True
            run.font.size = Pt(20)
        elif n:
            document.add_page_break()
        add_page(document, path, text, checks)

    out.parent.mkdir(parents=True, exist_ok=True)
    document.save(out)
    scan(out, pages, checks)
    open_check(out, title)
    try:
        shown = out.resolve().relative_to(ROOT)
    except ValueError:
        shown = out
    print(f"{shown}  {out.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
