"""Check that scripts/make_docx.py writes the course's .docx as promised, and refuses one it
must not ship.

    python3 tests/make_docx_test.py

The .docx ships with a release of the course, long after the build has checked site/, so it
carries its own guards (DESIGN.md section 4, D24): the site's private-content scan runs
inside the file it writes, and a hit deletes the file. A guard that silently stopped running
would look exactly like a clean export, so each refusal is proved here on a fixture that
should trip it. The metadata is checked against DESIGN.md's byline, read here on its own and
never typed: build/NameTest.java allows the author's name only in the three bylines.

Fixture volumes are made under build/.work/docx/test-fixtures/, and the script runs with the
venv's Python, which needs python-docx; without it this test fails and prints the setup
command, never skips.
"""

import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "make_docx.py"
PYTHON = ROOT / "build" / ".work" / "docx-venv" / "bin" / "python"
FIXTURES = ROOT / "build" / ".work" / "docx" / "test-fixtures"
SETUP = ("python3 -m venv build/.work/docx-venv && "
         "build/.work/docx-venv/bin/pip install python-docx==1.2.0")
COMMENTS = "generated by python-docx. Claude Opus 5.5"
BYLINE = "—built with Claude"
W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
DC = "{http://purl.org/dc/elements/1.1/}"

PAGES = {
    "00-front-matter.md": (
        "# Fixture: A Course for the Test\n\n"
        "Front matter prose with `code`, **bold**, *italic* and a "
        "[link](https://example.invalid/).\n\n"
        "> A quoted line.\n\n"
        "| Column | Other |\n| --- | --- |\n| cell one | `cell code` |\n\n"
        "- a bullet\n- another bullet\n\n"
        "1. first step\n2. second step\n"),
    "ch01-first.md": (
        "<!-- part: Part One -->\n# Chapter 1: First\n\n## A section\n\n"
        "```java\nvoid main() {\n    IO.println(\"fixture code line\");\n}\n```\n\n"
        "```output\nfixture output line\n```\n\n"
        "```text\nfixture text fence line\n```\n\n"
        "**1.** Print the answer.\n\n"
        "```java\nvoid main() {\n    IO.println(\"the author's own answer\");\n}\n```\n\n"
        "```output\nthe author's answer prints this\n```\n\n"
        "**2.** Predict what this prints.\n\n"
        "```java\nvoid main() {\n    IO.println(\"predict me\");\n}\n```\n\n"
        "```output\nthe predicted answer\n```\n"),
    "99-appendices.md": "# Appendices\n\n## Appendix A\n\n1. one again\n2. two again\n",
}
CHECKS = {
    "ch01-first#2": {"kind": "output", "expected": "x",
                     "starter": "void main() {\n    // fixture starter line\n}\n"},
    "ch01-first#3": {"kind": "predict"},
}


def byline_name():
    """The name DESIGN.md's byline gives: what stands between its "Byline:" label and
    "—built with Claude". Found here on its own, never imported from the script."""
    found = re.findall(r"Byline:\s*([^\n]*?)" + BYLINE,
                       (ROOT / "DESIGN.md").read_text(encoding="utf-8"))
    return found[0].strip() if len(found) == 1 else None


def make_volume(base, name, extra=""):
    """A fixture volume: the pages above, with `extra` added to chapter 1, and a
    _solutions.md and a practice page that the export must never read."""
    vol = base / name
    (vol / "content").mkdir(parents=True)
    (vol / "practice").mkdir()
    (vol / "volume.json").write_text(json.dumps(
        {"number": 1, "title": "Fixture", "subtitle": "A Course for the Test"}))
    for page, text in PAGES.items():
        (vol / "content" / page).write_text(text + (extra if page.startswith("ch01") else ""))
    (vol / "content" / "_checks.json").write_text(json.dumps(CHECKS))
    (vol / "content" / "_solutions.md").write_text(
        "## ch01-first#2\n\nWorked solutions\n\n```java\nvoid main() {\n"
        "    IO.println(\"a worked solution line\");\n}\n```\n")
    (vol / "practice" / "ch01-first-practice.md").write_text(
        "# Practice\n\nfixture practice line\n")
    return vol


def export(vol, out):
    return subprocess.run([str(PYTHON), str(SCRIPT), "--volume", str(vol), "--out", str(out)],
                          capture_output=True, text=True, cwd=ROOT)


def paragraphs(docx):
    """word/document.xml's paragraphs in order, table cells' included, as (text, style,
    runs), each run (text, its rPr element or None)."""
    with zipfile.ZipFile(docx) as archive:
        body = ElementTree.fromstring(archive.read("word/document.xml"))
    out = []
    for p in body.iter(W + "p"):
        runs = []
        for r in p.iter(W + "r"):
            text = "".join({W + "t": e.text or "", W + "tab": "\t", W + "br": "\n"}
                           .get(e.tag, "") for e in r)
            runs.append((text, r.find(W + "rPr")))
        style = p.find(f"{W}pPr/{W}pStyle")
        out.append(("".join(t for t, _ in runs),
                    None if style is None else style.get(W + "val"), runs))
    return out


def run_holding(paras, text, exact=True):
    """The rPr of the first run whose text is (or, not exact, holds) `text`."""
    for _, _, runs in paras:
        for t, props in runs:
            if t == text or (not exact and text in t):
                return props
    return None


def prop(props, tag, attr="val"):
    el = None if props is None else props.find(W + tag)
    return None if el is None else el.get(W + attr, "")


def numbered_apart(docx):
    """True when the fixture's two numbered lists each have a numbering of their own that
    starts at 1. Word numbers every "List Number" paragraph in one sequence otherwise."""
    with zipfile.ZipFile(docx) as archive:
        body = ElementTree.fromstring(archive.read("word/document.xml"))
        numbering = ElementTree.fromstring(archive.read("word/numbering.xml"))
    ids = [p.find(f"{W}pPr/{W}numPr/{W}numId") for p in body.iter(W + "p")
           if p.find(f"{W}pPr/{W}pStyle[@{W}val='ListNumber']") is not None]
    ids = [None if i is None else i.get(W + "val") for i in ids]
    starts = {n.get(W + "numId"): n.find(f"{W}lvlOverride[@{W}ilvl='0']/{W}startOverride")
              for n in numbering.iter(W + "num")}
    return (len(ids) == 4 and ids[0] == ids[1] and ids[2] == ids[3] and ids[0] != ids[2]
            and all(starts.get(i) is not None and starts[i].get(W + "val") == "1"
                    for i in ids))


def main():
    results = []

    def check(label, ok, detail=""):
        results.append(ok)
        print(f"  {'ok  ' if ok else 'FAIL'}  {label}{'' if ok else f'  ({detail})'}")

    ready = PYTHON.exists() and subprocess.run([str(PYTHON), "-c", "import docx"],
                                               capture_output=True).returncode == 0
    check("the venv's Python imports python-docx", ready, f"set it up first: {SETUP}")
    if not ready:
        print(f"\n{len(results)} check(s), {results.count(False)} failed")
        sys.exit(1)

    # A check on the test's own reading: a wrong reading of DESIGN.md (the whole line, say)
    # would agree with the same wrong reading in the script, and the Author check would pass.
    name = byline_name()
    front = (ROOT / "volumes" / "vol1" / "content" / "00-front-matter.md").read_text(
        encoding="utf-8")
    check("DESIGN.md's byline gives the name the course's front matter starts its byline "
          "with (D124)",
          bool(name) and any(line.startswith(name + BYLINE) for line in front.splitlines()),
          "the name read from DESIGN.md is not the front matter's")

    FIXTURES.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=FIXTURES) as tmp:
        tmp = Path(tmp)

        out = tmp / "clean.docx"
        done = export(make_volume(tmp, "clean"), out)
        check("a clean volume exports, exit 0", done.returncode == 0 and out.exists(),
              f"exit {done.returncode}: {done.stdout}{done.stderr}")
        if out.exists():
            with zipfile.ZipFile(out) as archive:
                core = ElementTree.fromstring(archive.read("docProps/core.xml"))
            author = core.findtext(DC + "creator")
            check("Author is DESIGN.md's byline name", author == name,
                  f"got {author!r}, not the byline's name")
            title = core.findtext(DC + "title")
            check("Title is volume.json's title and subtitle, joined with \": \"",
                  title == "Fixture: A Course for the Test", f"got {title!r}")
            comments = core.findtext(DC + "description")
            check(f"Comments is {COMMENTS!r}", comments == COMMENTS, f"got {comments!r}")

            paras = paragraphs(out)
            text = "\n".join(t for t, _, _ in paras)
            order = ["Fixture: A Course for the Test", "Part One", "Chapter 1: First",
                     "fixture code line", "fixture output line", "fixture text fence line",
                     "Appendices", "Appendix A"]
            at = [text.find(s) for s in order]
            check("the front matter, then the chapter's headings, code and output, then the "
                  "appendices, in order",
                  -1 not in at and at == sorted(at), f"positions {dict(zip(order, at))}")

            code = run_holding(paras, "fixture code line", exact=False)
            output = run_holding(paras, "fixture output line", exact=False)
            check("a program is set in Menlo, its output in Menlo, muted grey",
                  prop(code, "rFonts", "ascii") == "Menlo" and prop(code, "color") is None
                  and prop(output, "rFonts", "ascii") == "Menlo"
                  and prop(output, "color") == "606060",
                  "the fences are not styled as the Python course's .docx styles them")

            styles = {t: s for t, s, _ in paras}
            check("inline code, bold, italic and links, a quote, a table and lists are "
                  "rendered, not printed as Markdown",
                  "Front matter prose with code, bold, italic and a link." in styles
                  and prop(run_holding(paras, "code"), "rFonts", "ascii") == "Menlo"
                  and prop(run_holding(paras, "bold"), "b") is not None
                  and prop(run_holding(paras, "italic"), "i") is not None
                  and styles.get("A quoted line.") == "IntenseQuote"
                  and styles.get("a bullet") == "ListBullet"
                  and styles.get("first step") == "ListNumber"
                  and "cell one" in styles and "cell code" in styles
                  and not any(mark in text for mark in ("**", "`", "](", "> ", "| ")),
                  "a construct is missing, unstyled or printed as Markdown")
            check("each numbered list counts from 1 on its own", numbered_apart(out),
                  "two numbered lists share one numbering, so the second goes on from the first")
            check("a box shows what its page shows: its starter in place of the author's fence, "
                  "and no stated output under a starter or predict box (D40(b))",
                  "fixture starter line" in text and "predict me" in text
                  and not any(s in text for s in ("the author's own answer",
                                                  "the author's answer prints this",
                                                  "the predicted answer")),
                  "the author's answer or a held-back output reached the .docx")
            check("practice pages and _solutions.md are not read",
                  not any(s in text for s in ("fixture practice line", "Worked solutions",
                                              "a worked solution line")),
                  "text from practice/ or _solutions.md reached the .docx")
        else:
            check("the clean file's metadata and text can be read", False, "no file was written")

        if sys.platform == "darwin":
            check("the open check runs on macOS (textutil read the file and found the title)",
                  "open check: textutil reads it" in done.stdout, done.stdout + done.stderr)
        else:
            check(f"the open check says it was skipped on {sys.platform}",
                  "open check skipped" in done.stdout, done.stdout + done.stderr)

        for marker in ("Worked solutions", "ANSWER KEY"):
            label = marker.split()[0].lower()
            out = tmp / f"leak-{label}.docx"
            done = export(make_volume(tmp, f"leak-{label}", f"\n{marker}\n"), out)
            said = done.stdout + done.stderr
            check(f"a page holding {marker!r} is refused, exit 1", done.returncode == 1,
                  f"exit {done.returncode}: {said.strip()}")
            check("  and no file is left behind", not out.exists(), f"{out.name} is still there")
            check("  and the message names the marker and the page",
                  repr(marker) in said and "ch01-first.md" in said, said.strip())

    print(f"\n{len(results)} check(s), {results.count(False)} failed")
    sys.exit(1 if False in results else 0)


if __name__ == "__main__":
    main()
